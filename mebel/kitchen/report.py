    L.append(_md_table(["Итог", "Проверка", "Что"], [(LEVEL_RU.get(f.level, f.level), f.check, f.text)
                                                     for f in findings]))
    L.append("\n## Допущения (решил сам, ждут подтверждения)\n")
    L.append(_md_table(["Что", "Принято", "Почему"], spec.assumptions(k)))
    L.append("\n## Вопросы и замер\n")
    for i, t in enumerate(sh["questions"], 1):
        L.append(f"{i}. {t}")
    L.append("\n## Второй этап — присадка и файлы для станка\n")
    st = k.drill_stats
    if st:
        dx = os.path.join(out_dir, "dxf")
        cnt = {d: len(os.listdir(os.path.join(dx, d))) for d in ("parts", "sheets", "fasady", "ops")
               if os.path.isdir(os.path.join(dx, d))}
        hole = [f for f in findings if f.check in ("отверстия", "крепёж", "петли (присадка)")]
        L.append(f"- Присадка посчитана из той же модели: конфирматов {st['confirmat']}, петель {st['hinge']}, "
                 f"отверстий под полкодержатели {st['shelf_pin']} (пропущено занятых {st['skipped_pins']}).")
        L.append(f"- Файлы `dxf/`: деталей {cnt.get('parts', 0)}, листов {cnt.get('sheets', 0)}, фасадов "
                 f"{cnt.get('fasady', 0)}, операций для постпроцессора {cnt.get('ops', 0)}; все DXF прочитаны обратно "
                 "(ezdxf) и сверены с расчётом (отверстия, контур, вырезы). Станок не задан — G-code нет.")
        for f in hole:
            L.append(f"- Проверка «{f.check}»: {f.text}")
        for t in st["moved_hinges"]:
            L.append(f"- Петли: {t}")
        L.append("- Не на станке (по месту/по кондуктору): " + "; ".join(st["not_cnc"]) + ".")
    for t in sh.get("stage2", []):
        L.append(f"- {t}")
    L.append("\n## Как пересобрать\n")
    L.append(f"```\npython -m mebel.kitchen products/{k.cfg['kitchen']['id']}.yaml "
             "--preview            # без Blender: снимки 3D (SwiftShader)\n"
             f"python -m mebel.kitchen products/{k.cfg['kitchen']['id']}.yaml --render "
             "           # рендеры Blender (CPU, ~10 мин) + PDF\n```")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    return path
